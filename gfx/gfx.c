/* ===== Структура multiboot_info (только нужные поля) ===== */
typedef struct
{
    unsigned int flags;
    unsigned int mem_lower;
    unsigned int mem_upper;
    unsigned int boot_device;
    unsigned int cmdline;
    unsigned int mods_count;
    unsigned int mods_addr;
} multiboot_info_t;

/* Поля графической информации идут ПОСЛЕ базовых 20 байт.
   Доступ к ним — только если бит 5 (GRAPHICS_BOOT) в flags == 1. */
#define MB_INFO_GFX_BASE 20

static volatile unsigned int* fb = 0;   /* фреймбуфер (32 bpp) */
static int fb_width = 0;
static int fb_height = 0;
static int fb_pitch = 0;                /* байт на строку */
static int active = 0;

int gfx_init(void* mbi_addr)
{
    multiboot_info_t* mbi = (multiboot_info_t*)mbi_addr;
    volatile unsigned char* p;
    unsigned int mode_type;

    if (mbi == 0 || !(mbi->flags & (1u << 5)))
    {
        return -1; /* GRUB не дал графику, остались в текстовом режиме */
    }

    p = (volatile unsigned char*)mbi + MB_INFO_GFX_BASE;

    /* Читаем "в лоб", по 4 байта, без выравнивания структур */
    fb_width  = *(const unsigned int*)(p + 0);
    fb_height = *(const unsigned int*)(p + 4);
    fb_pitch  = *(const unsigned int*)(p + 8);
    mode_type = *(const unsigned int*)(p + 12);

    if (mode_type != 0)
    {
        return -1; /* тип 0 = линейный RGB-фреймбуфер */
    }

    fb = (volatile unsigned int*)(*(const unsigned int*)(p + 16));
    active = 1;
    return 0;
}

int gfx_is_active(void)
{
    return active;
}

void gfx_fill_rect(int x, int y, int w, int h, unsigned int color)
{
    int i, j;

    if (!active) return;

    for (j = 0; j < h; j++)
    {
        int yy = y + j;
        if (yy < 0 || yy >= fb_height) continue;

        for (i = 0; i < w; i++)
        {
            int xx = x + i;
            if (xx < 0 || xx >= fb_width) continue;

            fb[(yy * fb_pitch + xx * 4) / 4] = color;
        }
    }
}

