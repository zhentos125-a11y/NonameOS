/* Таблица: ASCII -> индекс в шрифте */
static int glyph_index(char c)
{
    if (c == ' ') return 0;
    if (c >= '!' && c <= '~') return (c - '!') + 1;
    return 0;
}

void gfx_draw_char(int x, int y, char c, unsigned int color)
{
    const unsigned char* g = font[glyph_index(c)];
    int row, col;

    if (!active) return;

    for (row = 0; row < 8; row++)
    {
        unsigned char bits = g[row];
        for (col = 0; col < 8; col++)
        {
            if (bits & (0x80 >> col))
            {
                gfx_fill_rect(x + col, y + row, 1, 1, color);
            }
        }
    }
}

void gfx_draw_text(int x, int y, const char* s, unsigned int color)
{
    while (*s)
    {
        gfx_draw_char(x, y, *s++, color);
        x += 8;
    }
}

/* ===== Мини-оконный менеджер ===== */

void draw_window(Window* win)
{
    if (!active || !win) return;

    /* Тень окна */
    gfx_fill_rect(win->x + 4, win->y + 4, win->w, win->h, GFX_BLACK);

    /* Рамка (серая) */
    gfx_fill_rect(win->x, win->y, win->w, win->h, GFX_GRAY);

    /* Внутренняя область (цвет фона окна) */
    gfx_fill_rect(win->x + 2, win->y + 22, win->w - 4, win->h - 24, win->bg);

    /* Заголовок (тёмно-синяя полоса) */
    gfx_fill_rect(win->x + 2, win->y + 2, win->w - 4, 18, GFX_BLUE);

    /* Текст заголовка */
    gfx_draw_text(win->x + 8, win->y + 7, win->title, GFX_WHITE);
}

/* Два тестовых окна и фон — "рабочий стол" */
static Window win_calc = { 40,  60, 320, 200, GFX_DGRAY, "Calculator"};
static Window win_fs   = { 420, 100, 340, 260, GFX_BLACK, "Files"};

void gfx_refresh(void)
{
    if (!active) return;

    /* Фон экрана */
    gfx_fill_rect(0, 0, fb_width, fb_height, GFX_BLUE);

    draw_window(&win_calc);
    draw_window(&win_fs);
}

void gfx_test_desktop(void)
{
    gfx_refresh();

    gfx_draw_text(win_calc.x + 10, win_calc.y + 30, "2 + 2 =", GFX_WHITE);
    gfx_draw_text(win_calc.x + 10, win_calc.y + 45, "Result: 4", GFX_CYAN);
    gfx_draw_text(win_fs.x + 10, win_fs.y + 30, "/ (root)", GFX_WHITE);
}

